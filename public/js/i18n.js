export function t(key, lang = 'en') {
  const dict = T[lang] || T.en;
  return dict[key] !== undefined ? dict[key] : (T.en[key] || key);
}

export function translateDOM(lang = 'en') {
  const dict = T[lang] || T.en;

  document.querySelectorAll('[data-i]').forEach((el) => {
    const key = el.dataset.i;
    const text = dict[key] !== undefined ? dict[key] : T.en[key];
    if (text !== undefined) {
      el.textContent = text;
    }
  });

  document.querySelectorAll('[data-ip]').forEach((el) => {
    const key = el.dataset.ip;
    const ph = dict[key] !== undefined ? dict[key] : T.en[key];
    if (ph !== undefined) {
      el.setAttribute('placeholder', ph);
    }
  });
}
